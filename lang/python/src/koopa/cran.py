"""R package repository management for r.acidgenomics.com.

Cloud-native approach: S3 is the source of truth. No local git repo or drat
package required. Tarballs are uploaded directly; PACKAGES manifests are
regenerated by streaming only the DESCRIPTION file from each tarball and using
S3 ETags (== MD5 for single-part uploads) for checksums.
"""

import gzip
import io
import json
import os
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

_BUCKET = "r-REDACTED_ACCOUNT_ID-us-east-1-an"
_S3_URI = f"s3://{_BUCKET}"
_PROFILE = "acidgenomics"
_CLOUDFRONT_DISTRIBUTION_ID = "REDACTED_CF_DIST_ID"
_INDEX_URL = "https://r.acidgenomics.com/"

# CloudFront paths invalidated after every publish (manifests only — tarballs are immutable).
_CLOUDFRONT_PATHS = [
    "/bin/macosx/sonoma-arm64/contrib/*/PACKAGES*",
    "/src/contrib/PACKAGES*",
]

# Binary prefix where we actively publish. Only the latest macOS (Sequoia) on Apple Silicon.
_ACTIVE_BINARY_PREFIX = "bin/macosx/sonoma-arm64/contrib"

# Skeleton binary prefixes — empty PACKAGES manifests so R clients on these platforms
# fall back to source silently instead of warning about a missing index.
# Add a new entry whenever a new R minor is released.
_SKELETON_BINARY_PREFIXES: list[str] = [
    # big-sur-arm64: historical binaries deleted; keep empty index for older macOS arm64 Macs.
    "bin/macosx/big-sur-arm64/contrib/4.3",
    "bin/macosx/big-sur-arm64/contrib/4.4",
    "bin/macosx/big-sur-arm64/contrib/4.5",
    "bin/macosx/big-sur-arm64/contrib/4.6",
]

# DCF fields written to PACKAGES for source packages (in order).
_SOURCE_FIELDS = [
    "Package",
    "Version",
    "Depends",
    "Imports",
    "Suggests",
    "License",
    "MD5sum",
    "NeedsCompilation",
]

# Additional fields for binary PACKAGES.
_BINARY_EXTRA_FIELDS = ["Built", "File"]

# R script to build source + binary tarballs.
# Sentinels PKG_DIR, BUILD_DIR, and INDEX_URL are replaced before eval.
# BUILD_DIR is a Python-managed temp dir so tarballs survive the R session.
_BUILD_R = """\
stopifnot(requireNamespace("desc", quietly = TRUE))
pkg <- PKG_DIR
td <- BUILD_DIR
descFile <- file.path(pkg, "DESCRIPTION")
stopifnot(file.exists(descFile))
name <- desc::desc_get_field("Package", file = descFile)
version <- desc::desc_get_field("Version", file = descFile)
owd <- setwd(td)
on.exit(setwd(owd), add = TRUE)
R <- file.path(R.home(), "bin", "R")
message(sprintf("Building %s %s.", name, version))
build_args <- c("CMD", "build", "--log", "--md5",
    "--no-build-vignettes", "--no-manual", shQuote(pkg))
system2(R, build_args, stderr = TRUE)
src <- file.path(td, paste0(name, "_", version, ".tar.gz"))
stopifnot(file.exists(src))
if (file.size(src) > 2e6) stop(sprintf("Source package too large: %s", src))
system2(R, c("CMD", "INSTALL", "--build", shQuote(src)), stderr = TRUE)
bin <- file.path(td, paste0(name, "_", version, ".tgz"))
stopifnot(file.exists(bin))
if (file.size(bin) > 5e6) stop(sprintf("Binary package too large: %s", bin))
bin_url <- contrib.url(INDEX_URL, type = "binary")
bin_subpath <- sub(paste0("^", gsub("/$", "", INDEX_URL), "/?"), "", bin_url)
cat(src, bin, bin_subpath, sep = "\\n")
"""

# R one-liner to write PACKAGES.rds from a PACKAGES text file in the same dir.
_WRITE_RDS_R = """\
setwd(DIR)
pkgs <- read.dcf("PACKAGES")
saveRDS(pkgs, "PACKAGES.rds", compress = "xz")
"""


