def publish(
    package_dir: str,
    *,
    check: bool = True,
    deploy: bool = True,
    invalidate: bool = True,
) -> None:
    """Build and publish an R package to r.acidgenomics.com.

    Uploads tarballs directly to S3 and regenerates PACKAGES manifests
    by streaming DESCRIPTION files — no local git repo or drat required.

    Parameters
    ----------
    package_dir
        Path to an R package source directory (must contain DESCRIPTION).
    check
        Run R CMD check --as-cran --no-manual before building.
    deploy
        Upload to S3 and regenerate PACKAGES manifests after building.
    invalidate
        Invalidate CloudFront PACKAGES* caches (only when deploy=True).
    """
    from koopa.alert import alert

    pkg_path = Path(package_dir).expanduser().resolve()
    if not (pkg_path / "DESCRIPTION").is_file():
        msg = f"No DESCRIPTION found in '{pkg_path}'."
        raise FileNotFoundError(msg)

    if check:
        from koopa.r import r_check

        alert(f"Checking '{pkg_path.name}'.")
        r_check(str(pkg_path))

    alert(f"Building '{pkg_path.name}'.")
    with tempfile.TemporaryDirectory(prefix="koopa-r-build-") as build_dir:
        src_path, bin_path, bin_subpath = _r_build(str(pkg_path), build_dir)

        src_base = os.path.basename(src_path)
        bin_base = os.path.basename(bin_path)

        if deploy:
            # Package name from tarball basename: "goalie_0.7.9.tar.gz" → "goalie"
            pkg_name = src_base.rsplit("_", 1)[0]
            src_key = f"src/contrib/{src_base}"
            bin_key = f"{bin_subpath}/{bin_base}"

            alert(f"Archiving previous version of '{pkg_name}' in src/contrib.")
            _archive_old_source(pkg_name, src_base)

            alert(f"Uploading '{src_base}' to s3://{_BUCKET}/{src_key}.")
            _upload_package(src_path, src_key)

            alert(f"Uploading '{bin_base}' to s3://{_BUCKET}/{bin_key}.")
            _upload_package(bin_path, bin_key)

            alert("Regenerating src/contrib PACKAGES manifests.")
            _reindex_prefix("src/contrib", binary=False)

            alert(f"Regenerating {bin_subpath} PACKAGES manifests.")
            _reindex_prefix(bin_subpath, binary=True)

            if invalidate:
                alert("Invalidating CloudFront PACKAGES* caches.")
                _invalidate_cloudfront()

            alert(f"Published '{src_base}' to {_INDEX_URL}")
        else:
            alert(f"Built '{src_base}' and '{bin_base}' (deploy skipped).")


def archive_src(*, invalidate: bool = True) -> None:
    """Move superseded source tarballs in src/contrib/ to Archive/<Pkg>/.

    Groups tarballs by package name, keeps only the latest version of each
    in the flat src/contrib/ directory, and S3-mv's superseded versions to
    src/contrib/Archive/<Pkg>/<filename>. Regenerates PACKAGES manifests
    and optionally invalidates CloudFront.

    Parameters
    ----------
    invalidate
        Invalidate CloudFront PACKAGES* caches after archiving.
    """
    from koopa.alert import alert

    alert("Listing src/contrib packages.")
    objects = _s3_list_packages("src/contrib")
    if not objects:
        alert("No packages found in src/contrib.")
        return

    # Group by package name, collect (version_tuple, filename, key) per package.
    from collections import defaultdict

    groups: dict[str, list[tuple[tuple[int, ...], str, str]]] = defaultdict(list)
    for obj in objects:
        filename = obj["Filename"]
        # Parse "PkgName_X.Y.Z.tar.gz" → name="PkgName", ver=(X,Y,Z)
        stem = filename[: -len(".tar.gz")]
        parts = stem.rsplit("_", 1)
        if len(parts) != 2:
            continue
        pkg_name, ver_str = parts
        try:
            ver_tuple = tuple(int(x) for x in ver_str.split("."))
        except ValueError:
            continue
        groups[pkg_name].append((ver_tuple, filename, obj["Key"]))

    aws = _aws()
    archived = 0
    for pkg_name, versions in groups.items():
        if len(versions) <= 1:
            continue
        # Sort descending; keep the first (latest), archive the rest.
        versions.sort(key=lambda t: t[0], reverse=True)
        for _, filename, key in versions[1:]:
            archive_key = f"src/contrib/Archive/{pkg_name}/{filename}"
            alert(f"Archiving '{filename}' → Archive/{pkg_name}/.")
            subprocess.run(
                [
                    aws,
                    "s3",
                    f"--profile={_PROFILE}",
                    "mv",
                    f"{_S3_URI}/{key}",
                    f"{_S3_URI}/{archive_key}",
                ],
                check=True,
            )
            archived += 1

    if archived:
        alert(f"Archived {archived} superseded tarball(s). Regenerating manifests.")
        _reindex_prefix("src/contrib", binary=False)
        if invalidate:
            _invalidate_cloudfront()
    else:
        alert("src/contrib is already clean — no superseded versions found.")


def publish_from_github(
    pkg_name: str,
    *,
    org: str = "acidgenomics",
    check: bool = False,
    invalidate: bool = True,
) -> None:
    """Clone an R package from GitHub and publish it to r.acidgenomics.com.

    Clones https://github.com/<org>/<pkg_name> into a temporary directory,
    builds source + binary tarballs, uploads them to S3, and regenerates
    PACKAGES manifests. The clone is cleaned up automatically.

    Parameters
    ----------
    pkg_name
        GitHub repository name (e.g. "r-goalie").
    org
        GitHub organisation. Defaults to "acidgenomics".
    check
        Run R CMD check before building. Off by default for batch builds.
    invalidate
        Invalidate CloudFront PACKAGES* caches after publishing.
    """
    import shutil

    from koopa.alert import alert

    git = shutil.which("git")
    if git is None:
        msg = "git is not installed."
        raise RuntimeError(msg)

    url = f"https://github.com/{org}/{pkg_name}"
    alert(f"Cloning '{url}'.")
    with tempfile.TemporaryDirectory(prefix="koopa-r-clone-") as clone_dir:
        subprocess.run(
            [git, "clone", "--depth=1", url, clone_dir],
            check=True,
        )
        publish(clone_dir, check=check, invalidate=invalidate)


def reindex(*, invalidate: bool = True) -> None:
    """Regenerate all PACKAGES manifests from current S3 bucket contents.

    Reindexes src/contrib (source packages) and the active binary prefix
    (sonoma-arm64/contrib/<Rver> paths found in S3). Also writes empty PACKAGES
    manifests to skeleton prefixes so R clients on those platforms fall back to
    source silently instead of warning about a missing index.

    Parameters
    ----------
    invalidate
        Invalidate CloudFront PACKAGES* caches after reindexing.
    """
    from koopa.alert import alert

    alert("Reindexing src/contrib.")
    _reindex_prefix("src/contrib", binary=False)

    # Active binary prefixes — only sonoma-arm64; discover all R versions present.
    active_prefixes = [
        p.rstrip("/") for p in _s3_list_binary_prefixes() if _ACTIVE_BINARY_PREFIX in p
    ]
    alert(f"Active binary prefixes: {active_prefixes}")
    for prefix in active_prefixes:
        _reindex_prefix(prefix, binary=True)

    # Skeleton prefixes — write empty manifests to suppress R client warnings.
    for prefix in _SKELETON_BINARY_PREFIXES:
        alert(f"Writing empty skeleton PACKAGES for '{prefix}'.")
        with tempfile.TemporaryDirectory() as tmp_dir:
            _upload_manifest("", prefix, tmp_dir)

    if invalidate:
        alert("Invalidating CloudFront PACKAGES* caches.")
        _invalidate_cloudfront()

    alert("Reindex complete.")


def deploy(*, invalidate: bool = True) -> None:
    """Alias for reindex() — kept for CLI symmetry and AcidDevTools compatibility.

    Parameters
    ----------
    invalidate
        Invalidate CloudFront PACKAGES* caches after reindexing.
    """
    reindex(invalidate=invalidate)
